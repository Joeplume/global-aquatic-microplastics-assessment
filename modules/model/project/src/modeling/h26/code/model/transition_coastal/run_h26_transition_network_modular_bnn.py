"""Strict H26 transition/coastal comparison on matched river-network support.

This domain adapter deliberately reuses the already established strict outer
fold, source-disjoint inner early stopping, CF3 interval calibration, and
paired observation-arm implementation from the freshwater network runner.  It
changes only the domain and the covariate contract; the freshwater runner is
not modified.

The baseline and challenger are evaluated on exactly the same records and
prediction cells with usable RiverATLAS network and upstream-source support.
All transition/coastal prediction rows remain in the output.  Unsupported rows
carry explicit support states and NA process predictions.  Detection metadata
never enters the mean model, so protocol-aware and detection-unaware q50 are
generated by the same fit and differ only in interval width.
"""

