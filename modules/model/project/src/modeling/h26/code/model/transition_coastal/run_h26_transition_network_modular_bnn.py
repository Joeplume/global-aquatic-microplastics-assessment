def require(condition: bool, message: str) -> None:
    if not condition:
        raise RuntimeError(message)


def numeric(values: pd.Series) -> np.ndarray:
    return pd.to_numeric(values, errors="coerce").to_numpy(float)


def branches_for_candidate(candidate: str) -> dict[str, tuple[str, ...]]:
    if candidate == "s0_same_network_support":
        return BASE_BRANCHES
    if candidate == "network_nodirection":
        return NETWORK_NODIRECTION_BRANCHES
    raise RuntimeError(f"Unknown transition/coastal candidate: {candidate}")


def network_features_for_candidate(candidate: str) -> tuple[str, ...]:
    return NETWORK_ONLY_FEATURES if candidate == "network_nodirection" else ()


def requested_features(branches: dict[str, tuple[str, ...]]) -> tuple[str, ...]:
    names = tuple(dict.fromkeys(name for values in branches.values() for name in values))
    forbidden = sorted(set(names) & FORBIDDEN_MEAN_FEATURES)
    require(not forbidden, f"Forbidden transition/coastal mean features requested: {forbidden}")
    return names


def network_support(frame: pd.DataFrame) -> np.ndarray:
    return (
        frame[NETWORK_STATUS].astype(str).isin(SUPPORTED_NETWORK_STATES)
        & frame[SOURCE_STATUS].astype(str).eq("observed")
    ).to_numpy()


def load_inputs(
    args: argparse.Namespace,
    branches: dict[str, tuple[str, ...]],
) -> tuple[pd.DataFrame, pd.DataFrame, dict[str, object]]:
    """Load the transition domain without dropping unsupported grid rows."""
    features = requested_features(branches)
    train_header = set(pd.read_csv(args.training, nrows=0).columns)
    grid_header = set(pd.read_csv(args.prediction, nrows=0).columns)
    required_train = {"stable_record_id", NETWORK_STATUS, SOURCE_STATUS, *features}
    required_grid = {
        "prediction_id", "longitude", "latitude", "prediction_domain",
        NETWORK_STATUS, SOURCE_STATUS, *features,
    }
    require(
        required_train.issubset(train_header),
        f"Training table missing {sorted(required_train - train_header)}",
    )
    require(
        required_grid.issubset(grid_header),
        f"Prediction table missing {sorted(required_grid - grid_header)}",
    )
    training = pd.read_csv(
        args.training,
        usecols=["stable_record_id", NETWORK_STATUS, SOURCE_STATUS, *features],
        low_memory=False,
    )
    grid = pd.read_csv(
        args.prediction,
        usecols=[
            "prediction_id", "longitude", "latitude", "prediction_domain",
            NETWORK_STATUS, SOURCE_STATUS, *features,
        ],
        low_memory=False,
    )
    observation = pd.read_csv(args.observation, low_memory=False)
    observation_columns = (
        "stable_record_id", "waterbody", "source_group", "observed_log10",
        "sizecorr_known_sd_log10", "unit_sd_log10", "sampling_year_effective_v1_3",
        "detection_method", "qaqc_total_score", "sizecorr_lower_used_um",
        "sizecorr_evidence_tier",
    )
    required_observation = {"stable_record_id", "waterbody", "source_group", "observed_log10"}
    require(
        required_observation.issubset(observation.columns),
        f"Observation table missing {sorted(required_observation - set(observation.columns))}",
    )
    observation = observation[[name for name in observation_columns if name in observation]].copy()
    records_all = training.merge(observation, on="stable_record_id", how="inner", validate="one_to_one")
    records_all = records_all.loc[records_all["waterbody"].eq(DOMAIN)].reset_index(drop=True)
    supported_records = network_support(records_all)
    records = records_all.loc[supported_records].reset_index(drop=True)
    require(len(records) >= 500, f"Too few supported transition/coastal records: {len(records):,}")

    grid = grid.loc[grid["prediction_domain"].eq(DOMAIN)].copy()
    grid = grid.rename(columns={"prediction_domain": "waterbody"}).reset_index(drop=True)
    require(len(grid) > 0, "No transition/coastal prediction rows")
    supported_grid = network_support(grid)
    caoa_frame = pd.read_csv(args.caoa, usecols=["prediction_id", "caoa_status"], low_memory=False)
    grid = grid.merge(caoa_frame, on="prediction_id", how="left", validate="one_to_one")
    require(grid["caoa_status"].notna().all(), "C-AOA join did not close")

    network_features = network_features_for_candidate(args.candidate)
    if network_features:
        train_missing = {
            name: int((~np.isfinite(numeric(records[name]))).sum())
            for name in network_features
        }
        grid_missing = {
            name: int((~np.isfinite(numeric(grid.loc[supported_grid, name]))).sum())
            for name in network_features
        }
        require(
            sum(train_missing.values()) <= 4,
            f"Supported transition/coastal records retain too many missing network values: {train_missing}",
        )
        require(
            sum(grid_missing.values()) <= 8,
            f"Supported transition/coastal grid retains too many missing network values: {grid_missing}",
        )
    else:
        train_missing, grid_missing = {}, {}

    return records, grid, {
        "candidate": args.candidate,
        "records_before_network_support": int(len(records_all)),
        "records_supported": int(len(records)),
        "records_excluded": int(len(records_all) - len(records)),
        "record_network_status_counts": {
            str(key): int(value)
            for key, value in records_all[NETWORK_STATUS].value_counts(dropna=False).items()
        },
        "record_source_status_counts": {
            str(key): int(value)
            for key, value in records_all[SOURCE_STATUS].value_counts(dropna=False).items()
        },
        "grid_rows_retained": int(len(grid)),
        "grid_supported": int(supported_grid.sum()),
        "grid_unsupported": int((~supported_grid).sum()),
        "grid_network_status_counts": {
            str(key): int(value)
            for key, value in grid[NETWORK_STATUS].value_counts(dropna=False).items()
        },
        "grid_source_status_counts": {
            str(key): int(value)
            for key, value in grid[SOURCE_STATUS].value_counts(dropna=False).items()
        },
        "network_feature_missing_supported_records": train_missing,
        "network_feature_missing_supported_grid": grid_missing,
        "support_policy": "river network observed_or_terminal AND upstream source observed",
        "matched_support_across_candidates": True,
    }


def configure_shared_strict_runner() -> None:
    """Inject the transition-only contract into the shared strict engine."""
    freshwater.DOMAIN = DOMAIN
    freshwater.NETWORK_STATUS = NETWORK_STATUS
    freshwater.SOURCE_STATUS = SOURCE_STATUS
    freshwater.SUPPORTED_NETWORK_STATES = SUPPORTED_NETWORK_STATES
    freshwater.BASE_BRANCHES = BASE_BRANCHES
    freshwater.NETWORK_NODIRECTION_BRANCHES = NETWORK_NODIRECTION_BRANCHES
    freshwater.NETWORK_NODIRECTION_ONLY_FEATURES = NETWORK_ONLY_FEATURES
    freshwater.branches_for_candidate = branches_for_candidate
    freshwater.network_features_for_candidate = network_features_for_candidate
    freshwater.requested_features = requested_features
    freshwater.network_support = network_support
    freshwater.load_inputs = load_inputs


def rewrite_domain_audits(args: argparse.Namespace) -> None:
    """Replace freshwater-only labels left by the shared output writer."""
    for arm in ("protocol_aware", "detection_unaware"):
        path = args.run_root / "S0" / arm / DOMAIN / "H26_UNIT_AUDIT.json"
        require(path.exists(), f"Shared strict runner did not write {path}")
        audit = json.loads(path.read_text(encoding="utf-8"))
        audit["status"] = "H26_TRANSITION_COASTAL_NETWORK_STRICT_DEVELOPMENT_NOT_RELEASE"
        audit["domain"] = DOMAIN
        audit["candidate"] = args.candidate
        audit["covariate_contract"] = {
            "baseline": "existing transition S0 process covariates",
            "challenger_additions": list(network_features_for_candidate(args.candidate)),
            "forbidden_mean_features": sorted(FORBIDDEN_MEAN_FEATURES),
            "matched_river_and_source_support": True,
            "regional_targets_used": False,
            "observation_metadata_affects_q50": False,
        }
        map_audit = audit.get("map", {})
        if "all_freshwater_rows_retained" in map_audit:
            map_audit["all_transition_coastal_rows_retained"] = map_audit.pop(
                "all_freshwater_rows_retained"
            )
        limits = audit.get("limits", [])
        audit["limits"] = [
            str(value)
            .replace("freshwater", "transition/coastal")
            .replace("Freshwater", "Transition/coastal")
            for value in limits
        ]
        path.write_text(json.dumps(audit, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def train(args: argparse.Namespace) -> int:
    configure_shared_strict_runner()
    shared_stdout = io.StringIO()
    with contextlib.redirect_stdout(shared_stdout):
        status = freshwater.train(args)
    rewrite_domain_audits(args)
    shared_summary: dict[str, object] = {}
    for line in reversed(shared_stdout.getvalue().splitlines()):
        try:
            parsed = json.loads(line)
        except json.JSONDecodeError:
            continue
        if isinstance(parsed, dict):
            shared_summary = parsed
            break
    print(json.dumps({
        "status": "H26_TRANSITION_COASTAL_NETWORK_STRICT_COMPLETED",
        "candidate": args.candidate,
        "fold": int(args.fold),
        "metrics": shared_summary.get("metrics", {}),
        "shared_strict_engine": "run_h26_freshwater_network_modular_bnn.py",
    }, ensure_ascii=False))
    return status


